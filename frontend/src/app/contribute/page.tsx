export const isAutoGeneratedOrGenericTitle = (currentTitle: string) => {
  if (!currentTitle || !currentTitle.trim()) return true;
  const lower = currentTitle.toLowerCase();
  return (
    lower.startsWith("whatsapp") ||
    lower.startsWith("img_") ||
    lower.startsWith("screenshot") ||
    lower.startsWith("document") ||
    lower.startsWith("file") ||
    lower.includes("hand note") ||
    lower.includes("handnote") ||
    lower.includes("examination paper") ||
    lower.includes("question paper") ||
    lower.includes("midterm question") ||
    lower.includes("final question") ||
    lower.includes("quiz & ct") ||
    lower.includes("lab manual") ||
    lower.includes("lab report") ||
    lower.includes("study material") ||
    lower.includes("course-in")
  );
};

